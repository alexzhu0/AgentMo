function renderRuntimeProfiles(blueprint) {
  const profiles = Array.isArray(blueprint.runtime_profiles) ? blueprint.runtime_profiles : [];
  if (profiles.length === 0) return "- No secondary runtime profiles recorded.";
  return profiles
    .map((sourceProfile) => {
      const profile = portableRuntimeProfile(sourceProfile);
      return `- ${profile.id} (${profile.role}, ${profile.status}): ${profile.purpose}\n  - Owned surfaces: ${profile.owned_surfaces.join(", ")}\n  - Evidence boundaries: ${profile.evidence_boundaries.join(", ")}${renderOptionalRuntimeProfileLines(profile)}`;
    })
    .join("\n");
}

