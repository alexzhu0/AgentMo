function renderRegistryBoundOpenClawRunbook(blueprint, workspaceDir) {
  const blueprintFile = `examples/${blueprint.agent_id}.agentmo.json`;
  const blueprintBindings = (command, optional = {}) => renderDigestBindings(command, {
    blueprint: "$BLUEPRINT",
    ...optional,
  });
  return `# ${blueprint.agent_id} OpenClaw Runbook

This runbook is evidence-first. Runtime evidence does not certify OpenClaw domain parity or change blueprint status. Birth, eval, delivery, and observe are Produce-internal gates or proposals, not extra lifecycle stages.

OpenClaw target mutations require Node.js \`${OPENCLAW_TARGET_NODE_RANGE}\`. The authoritative check is \`node ./bin/agentmo.js runtime-check --target openclaw\`; copied instructions must run it before mutation instead of implementing their own predicate.

## 1. Review generated workspace

Generated workspace: \`${workspaceDir}\`.

Review \`workspace/AGENTS.md\`, \`workspace/SOUL.md\`, \`workspace/TOOLS.md\`, and \`workspace/skills/${blueprint.agent_id}/SKILL.md\` before binding real channels.

## 2. Produce an admitted runtime plan

\`run-plan\` is non-live planning. Each \`--digest\` below hashes the exact file bytes inside the invocation; it does not hash parsed JSON or reuse recorded provenance.

\`\`\`bash
BLUEPRINT="${blueprintFile}"
RUNTIME_PLAN="<temporary-root>/agentmo-${blueprint.agent_id}-runtime-plan.json"
node ./bin/agentmo.js run-plan "$BLUEPRINT" ${blueprintBindings("run-plan")} --target "openclaw" --workspace "${workspaceDir}" --agent "${blueprint.agent_id}" --provider "openai" --model "gpt-5.5" --thinking "off" --channel "local-cli" --transport "local" --message "Say exactly: ok" --json > "$RUNTIME_PLAN"
\`\`\`

For an OpenClaw source checkout, add \`--openclaw-source-root "<openclaw-source-root>"\` to both \`run-plan\` and \`run\`.

The runtime plan keeps provider, model, thinking, runtime, channel, selector, transport, fallbackFrom, fallbackEvidence, sandboxScope as separate fields. \`run\` allocates a fresh run-scoped execution unless an explicit selector is supplied; same-session replay requires explicit \`--resume-session\`. Multiline or over-limit prompts use \`--message-file\`.

## 3. Write managed run evidence

\`\`\`bash
RUN_OUT="<temporary-root>/agentmo-${blueprint.agent_id}-runs"
node ./bin/agentmo.js run "$RUNTIME_PLAN" ${renderDigestBindings("run", { "runtime-plan": "$RUNTIME_PLAN" })} --workspace "${workspaceDir}" --message "Say exactly: ok" --out "$RUN_OUT" --json
RUN_STATE="$RUN_OUT/runs/<run_id>/agentmo-run-state.json"
node ./bin/agentmo.js status "$BLUEPRINT" ${blueprintBindings("status", { "run-state": "$RUN_STATE" })} --run-state "$RUN_STATE" --json
\`\`\`

The default run is non-live and records \`executed:false\` with \`status:"declared"\`. It does not certify the runtime.

## 4. Report, replay, evaluate, and observe

\`\`\`bash
RUN_EVAL="<temporary-root>/agentmo-${blueprint.agent_id}-run-eval.json"
OBSERVATION="<temporary-root>/agentmo-${blueprint.agent_id}-observation.json"
node ./bin/agentmo.js run-report "$RUN_STATE" ${renderDigestBindings("run-report", { "run-state": "$RUN_STATE" })} --json
node ./bin/agentmo.js replay-run "$RUN_STATE" ${renderDigestBindings("replay-run", { "run-state": "$RUN_STATE" })} --out "<temporary-root>/agentmo-${blueprint.agent_id}-replay" --json
node ./bin/agentmo.js run-eval "$RUN_STATE" ${renderDigestBindings("run-eval", { "run-state": "$RUN_STATE" })} --expect-status "declared" --json > "$RUN_EVAL"
node ./bin/agentmo.js observe-run "$RUN_STATE" ${renderDigestBindings("observe-run", { "run-state": "$RUN_STATE" })} --out "$OBSERVATION" --json
node ./bin/agentmo.js observe "$OBSERVATION" ${renderDigestBindings("observe", { observation: "$OBSERVATION" })} --json
\`\`\`

\`observe-run\` is proposal-only and must not mutate the source run-state, blueprint, scaffold, runtime, or evals.

## 5. Close bounded domain and delivery evidence

\`\`\`bash
BUILD_STATE="<scaffold-root>/agentmo-build-state.json"
DOMAIN_CASES="<domain-cases.json>"
BIRTH_REPORT="<temporary-root>/agentmo-${blueprint.agent_id}-birth-report.json"
DOMAIN_EVAL="<temporary-root>/agentmo-${blueprint.agent_id}-domain-eval.json"
DELIVERY_REPORT="<temporary-root>/agentmo-${blueprint.agent_id}-delivery-report.json"
node ./bin/agentmo.js birth-report "$BLUEPRINT" ${blueprintBindings("birth-report", { "build-state": "$BUILD_STATE", "run-state": "$RUN_STATE", "run-eval": "$RUN_EVAL" })} --build-state "$BUILD_STATE" --run-state "$RUN_STATE" --run-eval "$RUN_EVAL" --expect-status "declared" --json > "$BIRTH_REPORT"
node ./bin/agentmo.js domain-eval "$BLUEPRINT" ${blueprintBindings("domain-eval", { "domain-cases": "$DOMAIN_CASES" })} --cases "$DOMAIN_CASES" --target "openclaw" --json > "$DOMAIN_EVAL"
node ./bin/agentmo.js delivery-report "$BLUEPRINT" ${blueprintBindings("delivery-report", { "build-state": "$BUILD_STATE", "run-state": "$RUN_STATE", "run-eval": "$RUN_EVAL", "birth-report": "$BIRTH_REPORT", "domain-eval": "$DOMAIN_EVAL" })} --build-state "$BUILD_STATE" --run-state "$RUN_STATE" --run-eval "$RUN_EVAL" --birth-report "$BIRTH_REPORT" --domain-eval "$DOMAIN_EVAL" --json > "$DELIVERY_REPORT"
\`\`\`

domain-eval fixtures certify only their bounded case suite. Delivery aggregation does not self-certify runtime, domain-wide quality, production approval, or customer-support readiness.

## 6. Optional isolated live local run

Live execution is explicit opt-in. Use isolated state; do not use production OpenClaw state for this smoke.

\`\`\`bash
node ./bin/agentmo.js runtime-check --target openclaw &&
RUN_ID="$(date +%Y%m%dT%H%M%S)-${blueprint.agent_id}-live" &&
export OPENCLAW_STATE_DIR="<temporary-root>/agentmo-openclaw-state-$RUN_ID" &&
WORKSPACE="<temporary-root>/agentmo-openclaw-workspace-$RUN_ID" &&
RUN_OUT="<temporary-root>/agentmo-openclaw-runs-$RUN_ID" &&
RUNTIME_PLAN="$RUN_OUT/agentmo-runtime-plan.json" &&
mkdir -p "$OPENCLAW_STATE_DIR" "$WORKSPACE" "$RUN_OUT" &&
node ./bin/agentmo.js run-plan "$BLUEPRINT" ${blueprintBindings("run-plan")} --target "openclaw" --workspace "$WORKSPACE" --openclaw-state-dir "$OPENCLAW_STATE_DIR" --agent "${blueprint.agent_id}" --provider "openai" --model "gpt-5.5" --thinking "off" --channel "local-cli" --transport "local" --message "Say exactly: ok" --json > "$RUNTIME_PLAN" &&
node ./bin/agentmo.js run "$RUNTIME_PLAN" ${renderDigestBindings("run", { "runtime-plan": "$RUNTIME_PLAN" })} --workspace "$WORKSPACE" --openclaw-state-dir "$OPENCLAW_STATE_DIR" --message "Say exactly: ok" --out "$RUN_OUT" --live --json
\`\`\`

The preflight above authorizes only the current process/runtime pairing. It is not live-success or domain-quality evidence.

## 7. Register and inspect explicitly

\`\`\`bash
node ./bin/agentmo.js runtime-check --target openclaw &&
openclaw agents add ${blueprint.agent_id} --workspace "${workspaceDir}" --non-interactive &&
openclaw agents list --bindings &&
openclaw sessions --agent ${blueprint.agent_id} --json
\`\`\`

Do not bind production channels until isolated live smoke, bounded domain eval, delivery evidence, and human review are complete. Keep trajectory inspection bounded; routine evidence excludes raw prompts, transcripts, tool arguments, tool results, and credential values.
`;
}


