import { renderDigestBindings } from "./artifact-subjects.js";
import { OPENCLAW_TARGET_NODE_RANGE } from "./runtime-compatibility.js";

export function buildTargetFiles(blueprint, targetId) {
  const files = buildBaseFiles(blueprint);
  if (targetId === "openclaw") addOpenClawFiles(files, blueprint);
  return files;
}

export function buildBaseFiles(blueprint) {
  const files = new Map([
    ["README.md", renderReadme(blueprint)],
    ["agent_policy.json", JSON.stringify(buildAgentPolicy(blueprint), null, 2) + "\n"],
    [`agents/${blueprint.architecture.main_agent}.md`, renderMainAgent(blueprint)],
    ["evals/CASES.md", renderEvalCases(blueprint)],
    ["evals/RUBRIC.md", renderRubric(blueprint)],
    ["history/VERSION_LEDGER.md", renderVersionLedger(blueprint)],
    ["history/EVIDENCE_INDEX.md", renderEvidenceIndex(blueprint)],
    ["governance/QUALITY_GATES.md", renderQualityGates(blueprint)],
  ]);

  for (const specialist of blueprint.architecture.specialists ?? []) {
    files.set(`agents/${specialist.id}.md`, renderSpecialistAgent(blueprint, specialist));
  }

  return files;
}

export function addOpenClawFiles(files, blueprint) {
  const workspaceDir = "openclaw/workspace";
  files.set("openclaw/README.md", renderOpenClawReadme(blueprint));
  files.set("openclaw/RUNBOOK.md", renderRegistryBoundOpenClawRunbook(blueprint, workspaceDir));
  files.set("openclaw/runtime_contract.md", renderOpenClawRuntimeContract(blueprint));
  files.set("openclaw/config/openclaw.agent.patch.json", JSON.stringify(buildOpenClawConfigPatch(blueprint, workspaceDir), null, 2) + "\n");
  files.set("openclaw/config/channel-bindings.examples.md", renderOpenClawBindingExamples(blueprint));
  files.set("openclaw/workspace/AGENTS.md", renderOpenClawAgents(blueprint));
  files.set("openclaw/workspace/SOUL.md", renderOpenClawSoul(blueprint));
  files.set("openclaw/workspace/USER.md", renderOpenClawUser(blueprint));
  files.set("openclaw/workspace/TOOLS.md", renderOpenClawTools(blueprint));
  files.set("openclaw/workspace/IDENTITY.md", renderOpenClawIdentity(blueprint));
  files.set(`openclaw/workspace/skills/${blueprint.agent_id}/SKILL.md`, renderOpenClawSkill(blueprint));
  files.set("openclaw/workspace/memory/README.md", renderOpenClawMemoryReadme(blueprint));
}

function buildAgentPolicy(blueprint) {
  return {
    version: "0.1",
    agent_id: blueprint.agent_id,
    runtime: blueprint.runtime,
    runtime_profiles: (blueprint.runtime_profiles ?? []).map(portableRuntimeProfile),
    status: blueprint.status,
    boundaries: {
      domain: blueprint.domain_genome.domain,
      purpose: blueprint.domain_genome.purpose,
      hard_failures: blueprint.domain_genome.hard_failures,
    },
    routing_modes: blueprint.architecture.routing_modes,
    tools: blueprint.tools.map((tool) => ({
      name: tool.name,
      purpose: tool.purpose,
      allowed_when: tool.allowed_when,
      forbidden_when: tool.forbidden_when,
      evidence_policy: tool.evidence_policy,
    })),
    evidence: blueprint.evidence,
    eval: blueprint.eval,
    governance: blueprint.governance,
  };
}

