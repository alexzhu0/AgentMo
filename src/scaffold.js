function renderOptionalRuntimeProfileLines(profile) {
  const lines = [];
  if (Array.isArray(profile.source_refs) && profile.source_refs.length > 0) {
    lines.push(`  - Source refs: ${profile.source_refs.join(", ")}`);
  }
  if (Array.isArray(profile.transfer_rules) && profile.transfer_rules.length > 0) {
    lines.push(`  - Transfer rules: ${profile.transfer_rules.join(", ")}`);
  }
  return lines.length > 0 ? `\n${lines.join("\n")}` : "";
}

function runtimeProfileIds(blueprint) {
  return Array.isArray(blueprint.runtime_profiles)
    ? blueprint.runtime_profiles.map((profile) => profile.id).filter((id) => typeof id === "string")
    : [];
}

function findRuntimeProfile(blueprint, id) {
  if (!Array.isArray(blueprint.runtime_profiles)) return undefined;
  return blueprint.runtime_profiles.find((profile) => profile && typeof profile === "object" && profile.id === id);
}

function renderToolContracts(blueprint) {
  return blueprint.tools
    .map(
      (tool) =>
        `### ${tool.name}\n\nPurpose: ${tool.purpose}\n\nAllowed when:\n${renderStringList(tool.allowed_when)}\n\nForbidden when:\n${renderStringList(tool.forbidden_when)}\n\nEvidence policy: ${tool.evidence_policy}`,
    )
    .join("\n\n");
}

function renderStringList(items) {
  return items.map((item) => `- ${item}`).join("\n");
}

function identityName(blueprint) {
  return blueprint.agent_id
    .split("-")
    .filter((part) => part.length > 0)
    .map((part) => `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`)
    .join(" ");
}
