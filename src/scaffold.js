function renderOpenClawRuntimeContract(blueprint) {
  const profile = findRuntimeProfile(blueprint, "openclaw");
  return `# ${blueprint.agent_id} OpenClaw Runtime Contract\n\n## Source profile\n\n- Runtime id: openclaw\n- Role: ${profile?.role ?? "unprofiled"}\n- Status: ${profile?.status ?? "unprofiled"}\n- Purpose: ${profile?.purpose ?? "No OpenClaw runtime profile recorded."}\n\n## Ownership table\n\n| Surface | Owner in OpenClaw target | AgentMother rule |\n| --- | --- | --- |\n| Model loop | OpenClaw embedded runtime unless provider/model policy selects a plugin runtime. | Record the selected runtime id; do not infer it from provider name. |\n| Canonical session history | OpenClaw session store under the selected agent scope. | Treat raw transcripts as audit artifacts, not normal prompt context. |\n| Workspace context | OpenClaw workspace files such as AGENTS.md, SOUL.md, USER.md, TOOLS.md, skills, memory. | Keep workspace private and version only non-secret guidance. |\n| Channel delivery | OpenClaw Gateway and channel bindings. | Treat channels as ingress/egress, not the domain genome. |\n| Dynamic tools and hooks | OpenClaw-owned tool loop and plugin hooks when supported by the active runtime. | Port hook behavior only when the target runtime exposes equivalent hooks. |\n| Evidence | Session summaries, trajectory tails, exports, eval records, release ledger. | Default to bounded summaries and explicit audit expansion. |\n\n## Evidence boundaries\n\n${renderStringList(profile?.evidence_boundaries ?? []) || "- No OpenClaw-specific evidence boundaries recorded."}\n\n## Transfer rules\n\n${renderStringList(profile?.transfer_rules ?? []) || "- No OpenClaw-specific transfer rules recorded."}\n\n## Source refs\n\n${renderStringList(profile?.source_refs ?? []) || "- No OpenClaw-specific source refs recorded."}\n\n## Hard failures inherited from blueprint\n\n${renderStringList(blueprint.domain_genome.hard_failures)}\n`;
}

function buildOpenClawConfigPatch(blueprint, workspaceDir) {
  return {
    note: "Merge manually into ~/.openclaw/openclaw.json; this is a patch-shaped fragment, not a full config.",
    agents: {
      list: [
        {
          id: blueprint.agent_id,
          name: identityName(blueprint),
          workspace: workspaceDir,
          skills: [blueprint.agent_id],
        },
      ],
    },
    bindings: [
      {
        agentId: blueprint.agent_id,
        match: {
          channel: "<channel>",
          accountId: "*",
        },
      },
    ],
  };
}

